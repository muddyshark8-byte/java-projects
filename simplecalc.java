class simplecalc
{
    public static void main (String [] args)
    {
        int num1 = 30;
        int num2= 40;
        char operator= '+';
        
        switch(operator)
       {
        case '+':
       System.out.println (num1 + num2);
        break;

        case '-':
       System.out.println (num1 - num2);
        break;

        case '/':
       System.out.println (num1 / num2);
        break;

        case '*':
       System.out.println (num1 * num2);


       } 
        



    }


}